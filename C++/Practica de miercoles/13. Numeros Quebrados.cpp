#include <iostream>

using namespace std;

int main() {
    double num1, num2;
    cout << "Ingrese dos numeros quebrados separados por un espacio: ";
    cin >> num1 >> num2;

    cout << "La suma es: " << num1 + num2 << endl;
    cout << "La resta es: " << num1 - num2 << endl;
    cout << "La multiplicacion es: " << num1 * num2 << endl;
    cout << "La division es: " << num1 / num2 << endl;

    return 0;
}

